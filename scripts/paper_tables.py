"""Generate manuscript tables and macros from the saved evaluation.

Called by paper_figures.py. No training, tuning, or account assumptions are changed here.
"""
import json
from pathlib import Path

import numpy as np

from core.config import HOURS_PER_YEAR

OUT = Path(__file__).resolve().parents[3] / 'report' / 'generated'
ROW = r' \\' + '\n'


def returns(equity):
    values = equity.to_numpy()
    return values / np.r_[10_000.0, values[:-1]] - 1


def table(filename, caption, label, columns, headers, rows, note=''):
    source = ('% Generated by implementation/study-1/scripts/paper_figures.py; do not edit numeric values manually.\n'
              '\\begin{table}[!htb]\n\\centering\n\\caption{' + caption + '}\n\\label{' + label + '}\n'
              '\\small\n\\begin{tabular}{' + columns + '}\n\\toprule\n' + ' & '.join(headers) + ROW + '\\midrule\n')
    source += ''.join(row + '\n' if isinstance(row, str) else ' & '.join(row) + ROW for row in rows)
    source += '\\bottomrule\n\\end{tabular}\n'
    # Definitions and interpretation belong in the surrounding manuscript, not below the tables.
    source += '\\end{table}\n'
    (OUT / filename).write_text(source)


def generate(data, frame):
    OUT.mkdir(parents=True, exist_ok=True)
    agent, bench = data['agent'], data['benchmarks']
    seeds = list(data['seeds'].values())
    keys = ('annual_return_pct', 'sharpe', 'max_drawdown_pct')
    sd = {key: float(np.std([s[key] for s in seeds], ddof=1)) for key in keys}
    bold = lambda value: r'\textbf{' + value + '}'
    f = lambda value, digits=1: f'${value:.{digits}f}$'.replace('$-', '$-') if value < 0 else f'{value:.{digits}f}'
    plain = lambda value, digits=1: f'{value:.{digits}f}'
    names = {'50 day MA': '50 day moving average', '200 day MA': '200 day moving average'}
    seed_sr = [s['sharpe'] for s in seeds]
    dd = [-s['max_drawdown_pct'] for s in seeds]
    macros = {'PPOCAGR': plain(agent['annual_return_pct']), 'PPOSR': plain(agent['sharpe'], 2),
              'PPODD': plain(-agent['max_drawdown_pct']), 'PPOCAGRSD': plain(sd['annual_return_pct']),
              'PPOSRSD': plain(sd['sharpe'], 2), 'PPODDSD': plain(sd['max_drawdown_pct']),
              'PPOSRMin': plain(min(seed_sr), 2), 'PPOSRMax': plain(max(seed_sr), 2),
              'PPODDMin': plain(min(dd)), 'PPODDMax': plain(max(dd)),
              'BHReturn': plain(bench['Buy and hold']['annual_return_pct']),
              'BHSR': plain(bench['Buy and hold']['sharpe'], 2),
              'TSMReturn': plain(bench['Time series momentum']['annual_return_pct']),
              'TSMSR': plain(bench['Time series momentum']['sharpe'], 2),
              'PPOChanges': f"{agent['position_changes']:,.0f}",
              'PPOLong': plain(100 * agent['long_share']), 'PPOShort': plain(100 * agent['short_share']),
              'PPOFlat': plain(100 * agent['flat_share']), 'PPOWin': plain(agent['win_rate_pct']),
              'TrainSR': plain(data['diagnostics']['mean_train_sharpe'], 2),
              'AnnualTestSR': plain(data['diagnostics']['mean_test_sharpe'], 2)}
    (OUT / 'numbers.tex').write_text('% Generated evaluation summaries.\n' + ''.join(
        '\\newcommand{\\' + key + '}{' + value + '}\n' for key, value in macros.items()))
    rows = [[bold('PPO agent'), bold(f(agent[keys[0]])), bold(f(agent[keys[1]], 2)), bold(f(-agent[keys[2]])),
             bold(f(agent['win_rate_pct'])), bold(f"{agent['position_changes']:,.0f}")]]
    for name, stats in bench.items():
        rows.append([names.get(name, name), f(stats[keys[0]]), f(stats[keys[1]], 2), f(-stats[keys[2]]),
                     f(stats['win_rate_pct']), f"{stats['position_changes']:,.0f}"])
    random = data['random']
    random_cagr = ((1 + random['total_return_pct'] / 100) ** (HOURS_PER_YEAR / len(frame)) - 1) * 100
    rows.append(['Random policy (median)', f(random_cagr), f(random['sharpe'], 2), f(-100 * random['max_drawdown']), '', ''])
    table('performance.tex', 'Performance over the test period.', 'tab:performance', 'lrrrrr',
          ['Strategy', r'CAGR (\%)', 'Sharpe', r'Max. DD (\%)', r'Win rate (\%)', 'Changes'], rows)
    rows = []
    for metric, heading, digits in [('return_pct', r'Return (\%)', 1), ('sharpe', 'Sharpe ratio', 2)]:
        if rows:
            rows.append(r'\midrule')
        rows.append(r'\multicolumn{7}{l}{' + heading + '}' + ROW.rstrip())
        rows.append([bold('PPO agent'), *[bold(f(v[metric], digits)) for v in agent['by_year'].values()]])
        for name, stats in bench.items():
            rows.append([names.get(name, name), *[f(v[metric], digits) for v in stats['by_year'].values()]])
    table('annual.tex', 'Returns and Sharpe ratios by calendar year.', 'tab:annual', 'lrrrrrr',
          ['Strategy', '2021', '2022', '2023', '2024', '2025', '2026*'], rows)
    rows = []
    for year, c in data['choices'].items():
        settings = c['settings']
        rows.append([year + ('*' if year == '2026' else ''), str(settings['hidden']), '1/' + str(round(1 / settings['eta'])),
                     str(c['passes']), f"{c['mean_sharpe']:.2f} ({c['standard_error']:.2f})"])
    table('choices.tex', 'Configuration selected for every test year.', 'tab:choices', 'lrrrr',
          ['Year', 'Width', r'$\eta$', 'Passes', 'Selection Sharpe'], rows,
          'Every selected configuration uses actor learning rate $8.38429594542857\\times10^{-5}$ and entropy '
          'coefficient 0.03. Mean SR and SE are the smoothed selection statistics, not test results or confidence bounds.')
    rows = []
    for year, d in data['descriptive_by_year'].items():
        rows.append([year + ('*' if year == '2026' else ''), f"{d['min']:,.0f}", f"{d['max']:,.0f}",
                     f(d['return_pct']), f(d['volatility_pct']), f(-d['max_drawdown_pct'])])
    table('descriptive.tex', 'Descriptive statistics of the hourly closing price by calendar year.', 'tab:descriptive', 'lrrrrr',
          ['Year', 'Low (USD)', 'High (USD)', r'Return (\%)', r'Volatility (\%)', r'Max. DD (\%)'], rows,
          'Complete years run from the initial midnight price to the next year\'s initial midnight price. The final '
          'settlement is 2 August 2026 at 00:00 UTC. Volatility is the sample standard deviation of hourly log returns '
          'multiplied by $\\sqrt{8760}$; annual return is the price ratio minus one.')
    rows, annual = [], []
    for number, (name, s) in enumerate(data['seeds'].items(), 1):
        seed = str(number)
        rows.append([seed, f(s[keys[0]]), f(s[keys[1]], 2), f(-s[keys[2]])])
        annual.append([seed, *[f(d['return_pct']) for d in s['by_year'].values()]])
    rows.append([bold('Mean'), bold(f(agent[keys[0]])), bold(f(agent[keys[1]], 2)), bold(f(-agent[keys[2]]))])
    annual.append([bold('Mean'), *[bold(f(d['return_pct'])) for d in agent['by_year'].values()]])
    table('seeds.tex', 'Results of the ten individual runs over the test period.', 'tab:seeds', 'lrrr',
          ['Run', r'CAGR (\%)', 'Sharpe', r'Max. DD (\%)'], rows)
    table('seed_annual.tex', 'Annual returns of the ten individual runs.', 'tab:seedannual', 'lrrrrrr',
          ['Run', '2021', '2022', '2023', '2024', '2025', '2026*'], annual)
